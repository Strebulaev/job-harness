"""M2-3 tests: JD parser + evidence-span post-check + normalizers.

Covers the M2-3 done-when:
- a unit test feeds a JD whose raw text does not contain the span the LLM
  claims for a field; after the post-check, the field is downgraded to
  "unknown" and the span is dropped;
- a unit test on ``normalizers.py`` converts ``$100/hr x 40 hr/wk`` to the
  correct USD/month with ``comp_confidence`` set;
- ``parse_jd`` on all 30 golden jobs (offline, FakeProvider) produces a
  valid ``JDParsed`` for each.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from jobharness.llm.fake_provider import FakeProvider
from jobharness.parse.jd_parser import parse_jd, verify_evidence_spans
from jobharness.parse.normalizers import normalize_compensation
from jobharness.schemas.jd import Compensation, JDParsed
from jobharness.settings import Settings

REPO_ROOT = Path(__file__).resolve().parents[2]
GOLDEN_DIR = REPO_ROOT / "eval_data" / "golden_jobs"
FIXTURES_DIR = REPO_ROOT / "tests" / "fixtures" / "llm"
CONFIG_EXAMPLE = REPO_ROOT / "config" / "config.example.yaml"
SIDECAR = GOLDEN_DIR / "expected_downgrades.json"

MODEL = "fake-parse-v1"
TEMPERATURE = 0.0


def _expected_downgrades() -> dict[str, list[str]]:
    """Which fields the post-check downgrades per golden job (generated by
    scripts/gen_parse_fixtures.py). If missing, the test treats every
    non-unknown field as expected to survive."""
    if not SIDECAR.exists():
        return {}
    return json.loads(SIDECAR.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def settings() -> Settings:
    return Settings.from_yaml(CONFIG_EXAMPLE)


@pytest.fixture(scope="module", autouse=True)
def db_session(tmp_path_factory) -> None:
    """Bind a session factory to a throwaway DB so ``log_llm_call`` writes
    rows instead of logging a failure (M1 convention, test_llm.py)."""
    from jobharness.db.models import Base
    from jobharness.db.session import init_session_factory, make_engine

    engine = make_engine(tmp_path_factory.mktemp("db") / "jh_test.db")
    Base.metadata.create_all(engine)
    init_session_factory(engine)
    yield


@pytest.fixture(scope="module")
def provider() -> FakeProvider:
    return FakeProvider(fixtures_dir=FIXTURES_DIR)


def test_evidence_span_downgrades_unsupported_field() -> None:
    """A claimed span that is not in the raw JD must be downgraded."""
    parsed = JDParsed.model_validate(
        {
            "title": "Senior Backend Engineer",
            "engagement_type": "contractor",  # LLM-claimed
            "remote_policy": "remote",
            "compensation": {
                "min": 1000,
                "max": 2000,
                "currency": "USD",
                "period": "month",
            },
            "evidence_spans": {
                "engagement_type": "independent contractor",  # NOT in the JD text
                "remote_policy": "Remote: worldwide",
                "compensation": "$1,000 - $2,000 per month",
            },
        }
    )
    jd_raw = (
        "Senior Backend Engineer. Remote: worldwide. "
        "Compensation: $1,000 - $2,000 per month."
    )
    result, downgraded = verify_evidence_spans(parsed, jd_raw)
    assert downgraded == ["engagement_type"]
    assert result.engagement_type == "unknown"
    assert "engagement_type" not in result.evidence_spans
    # Supported fields are kept.
    assert result.remote_policy == "remote"
    assert result.compensation is not None
    assert result.evidence_spans["remote_policy"] == "Remote: worldwide"
    # The result must re-validate cleanly.
    JDParsed.model_validate(result.model_dump())


def test_evidence_span_stale_span_on_unknown_field_removed() -> None:
    """A span on a field that is unknown/None/empty is stale and removed."""
    parsed = JDParsed.model_validate(
        {
            "title": "Some Job",
            "engagement_type": "unknown",
            "remote_policy": "remote",
            "evidence_spans": {
                "engagement_type": "contractor (stale span, field is unknown)",
                "remote_policy": "Remote: worldwide",
            },
        }
    )
    jd_raw = "Some Job. Remote: worldwide."
    result, downgraded = verify_evidence_spans(parsed, jd_raw)
    assert downgraded == []
    assert "engagement_type" not in result.evidence_spans
    assert result.evidence_spans["remote_policy"] == "Remote: worldwide"


def test_evidence_span_missing_span_downgrades() -> None:
    parsed = JDParsed.model_validate(
        {
            "title": "RAG Engineer",
            "engagement_type": "b2b",  # non-unknown, no span
            "evidence_spans": {},
        }
    )
    result, downgraded = verify_evidence_spans(parsed, "We need a RAG engineer.")
    assert downgraded == ["engagement_type"]
    assert result.engagement_type == "unknown"


def test_normalizer_hourly_100_hr_40_hrwk(settings: Settings) -> None:
    """$100/hr x 40 hr/wk -> 40 x 52/12 = 173.33 h/month -> $17,333.33/mo."""
    comp = Compensation(min=100, max=100, currency="USD", period="hour")
    norm = normalize_compensation(comp, settings, hours_per_week=(40, 40))
    assert norm.confidence == "low"
    expected = 100 * (40 * 52 / 12)
    assert norm.usd_min_month == pytest.approx(expected)
    assert norm.usd_max_month == pytest.approx(expected)
    assert norm.currency == "USD"
    assert norm.period == "hour"


def test_normalizer_hourly_default_120_hm(settings: Settings) -> None:
    comp = Compensation(min=25, max=35, currency="EUR", period="hour")
    norm = normalize_compensation(comp, settings)
    rate = settings.fx.rates.model_dump()["EUR"]
    assert norm.confidence == "low"
    assert norm.usd_min_month == pytest.approx(25 * rate * 120)
    assert norm.usd_max_month == pytest.approx(35 * rate * 120)


def test_normalizer_monthly_fx(settings: Settings) -> None:
    comp = Compensation(min=3000, max=5000, currency="EUR", period="month")
    norm = normalize_compensation(comp, settings)
    rate = settings.fx.rates.model_dump()["EUR"]
    assert norm.confidence == "high"
    assert norm.usd_min_month == pytest.approx(3000 * rate)
    assert norm.usd_max_month == pytest.approx(5000 * rate)


def test_normalizer_yearly(settings: Settings) -> None:
    comp = Compensation(min=36000, max=48000, currency="USD", period="year")
    norm = normalize_compensation(comp, settings)
    assert norm.confidence == "high"
    assert norm.usd_min_month == pytest.approx(3000)
