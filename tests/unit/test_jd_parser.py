def _golden_jobs() -> list[Path]:
    return sorted(
        p for p in GOLDEN_DIR.glob("*.json")
        if p.stem not in ("expected_downgrades", "baseline")
    )


@pytest.mark.parametrize("path", _golden_jobs(), ids=lambda p: p.stem)
async def test_parse_golden_job_offline(provider: FakeProvider, path: Path) -> None:
    """Every golden job must parse into a valid JDParsed via FakeProvider."""
    data = json.loads(path.read_text(encoding="utf-8"))
    jd_raw: str = data["jd_raw"]
    result = await parse_jd(
        jd_raw, provider, model=MODEL, temperature=TEMPERATURE, prompt_version="v1"
    )
    parsed = result.parsed
    # Re-validate: stored object must satisfy the schema.
    JDParsed.model_validate(parsed.model_dump())
    # The post-check must not have downgraded any field the golden labels say
    # must be non-unknown: the hand-authored expected_jd_parsed values carry
    # spans that are verbatim substrings of jd_raw, so they must survive.
    expected = data["expected_jd_parsed"]
    must_downgrade = set(_expected_downgrades().get(path.stem, []))
    # Every field the parser downgraded must have a span the generator
    # could not verify (i.e. not in the sidecar is allowed; in the
    # sidecar is a generator bug).
    unexpected = set(result.downgraded_fields) - must_downgrade
    assert not unexpected, (
        f"{path.name}: parser downgraded {sorted(unexpected)} "
        f"whose spans the generator verified"
    )
    # Every stored span must still verify against the raw JD.
    norm_raw = " ".join(jd_raw.lower().split())
    for field, span in parsed.evidence_spans.items():
        norm_span = " ".join(span.lower().split())
        assert norm_span in norm_raw, f"{path.name}: span for {field} not in jd_raw"

    # Fields the golden labels say must be non-unknown must either equal the
    # label value (survived the post-check) or be in the unknown/empty state
    # (the sidecar recorded the downgrade).
    expected = data["expected_jd_parsed"]
    for field, want in expected.items():
        if field == "evidence_spans":
            continue
        if want in ("unknown", None, [], ""):
            continue
        got = getattr(parsed, field)
        if isinstance(want, list) and field in (
            "must_have",
            "nice_to_have",
            "tech_stack",
            "responsibilities",
            "red_flags",
        ):
            if field in must_downgrade:
                assert got == [], (
                    f"{path.name}: {field}={got!r} should have been downgraded "
                    f"to [] (sidecar)"
                )
            continue  # list contents are LLM-selected; membership not asserted
        if isinstance(want, dict) and field in ("compensation", "required_overlap"):
            if field in must_downgrade:
                assert got is None, (
                    f"{path.name}: {field}={got!r} should have been downgraded "
                    f"to None (sidecar)"
                )
            continue
        if field == "hours_per_week" and isinstance(want, list):
            if field in must_downgrade:
                assert got is None, (
                    f"{path.name}: hours_per_week={got!r} should have been "
                    f"downgraded to None (sidecar)"
                )
            continue
        if isinstance(want, bool):
            if field in must_downgrade:
                assert got is None, (
                    f"{path.name}: {field}={got!r} should have been downgraded "
                    f"to None (sidecar)"
                )
            continue
        if field == "countries_allowed" and isinstance(want, list):
            if field in must_downgrade:
                assert got == [], (
                    f"{path.name}: countries_allowed={got!r} should have been "
                    f"downgraded to [] (sidecar)"
                )
            continue
        if field in must_downgrade:
            assert got == "unknown", (
                f"{path.name}: {field}={got!r} should have been downgraded "
                f"to 'unknown' (sidecar)"
            )
            continue
        assert got == want, f"{path.name}: {field} = {got!r}, expected {want!r}"
